@router.get('/api/speaking/practice/facets')
async def speaking_facets(req: Request):
    user = await core.current_user(req, active=True)
    if not user: return core.auth_error()
    channel = _channel(req)
    if channel is None: return core.j({'error': 'invalid_channel'}, 400)
    part = req.query_params.get('part')
    search = utf16_slice(req.query_params.get('q', ''), 120)
    where, args = _scope(channel, search=search)
    db = await core.pool()
    async with db.acquire() as conn:
        counts = await conn.fetch(f'''SELECT p.part::text AS part, count(*)::int AS count
            FROM speaking_prompts p WHERE {where} GROUP BY p.part ORDER BY p.part ASC''', *args)
        parts = [{'part': r['part'], 'count': int(r['count'])} for r in counts]
        matching = sum(r['count'] for r in parts)
        if not part:
            return core.j({'parts': parts, 'topics': [], 'topicCount': 0,
                           'hasMoreTopics': False, 'nextTopicCursor': None, 'matching': matching},
                          headers={'Cache-Control': 'no-store'})
        args.append(part)
        part_where = where + f' AND p.part=${len(args)}::speaking_part'
        cursor = req.query_params.get('topicCursor')
        topic_scope = part_where
        if cursor is not None:
            try: key = parse_topic_cursor(cursor)
            except InvalidCursor: return core.j({'error': 'invalid_cursor'}, 400)
            args.append(key)
            topic_scope += f' AND {_TOPIC_KEY} > ${len(args)}'
        rows = await conn.fetch(f'''SELECT {_TOPIC_KEY} AS key,
            min(nullif(btrim(p.topic), '')) AS title, count(*)::int AS count
            FROM speaking_prompts p WHERE {topic_scope}
            GROUP BY {_TOPIC_KEY} ORDER BY {_TOPIC_KEY} ASC LIMIT 501''', *args)
        total = await conn.fetchval(f'''SELECT count(DISTINCT {_TOPIC_KEY})::int
            FROM speaking_prompts p WHERE {part_where}''', *(args[:-1] if cursor is not None else args))
    more = len(rows) > 500
    topics = [{'key': r['key'], 'title': r['title'], 'count': int(r['count'])} for r in rows[:500]]
    return core.j({'parts': parts, 'topics': topics, 'topicCount': int(total or 0),
                   'hasMoreTopics': more,
                   'nextTopicCursor': _b64({'k': topics[-1]['key']}) if more and topics else None,
                   'matching': matching}, headers={'Cache-Control': 'no-store'})


def _study_support(raw: Any):
    """Match the Zod object's defaults, stripping unknown keys and refusing bad stored data."""
    if raw is None: raw = {}
    if not isinstance(raw, dict): return None
    output = {}
    for name in ('vocabularyHtml', 'modelAnswerHtml', 'ideasHtml'):
        v = raw.get(name, '')
        if not isinstance(v, str) or len(v.encode('utf-16-le', 'surrogatepass')) // 2 > 100000:
            return None
        output[name] = v
    vocab = raw.get('vocabulary', [])
    if not isinstance(vocab, list) or len(vocab) > 100: return None
    cleaned = []
    for w in vocab:
        if not isinstance(w, dict): return None
        item = {}
        for k, max_len, required in (('term', 120, True), ('definitionEn', 500, True),
                                      ('translationUz', 500, False), ('partOfSpeech', 30, False),
                                      ('exampleSentence', 500, False)):
            v = w.get(k, None if required else '')
            if not isinstance(v, str): return None
            v = v.strip()
            if (required and not v) or len(v.encode('utf-16-le', 'surrogatepass')) // 2 > max_len:
                return None
            item[k] = v
        cleaned.append(item)
    output['vocabulary'] = cleaned
    return output


@router.get('/api/speaking/prompts/{id}/support')
async def speaking_prompt_support(req: Request, id: str):
    user = await core.current_user(req, active=True)
    if not user: return core.auth_error()
    channel = 'ai' if req.query_params.get('channel') == 'ai' else 'practice_alone'
    where, args = _scope(channel)
    args.append(id)
    db = await core.pool()
    async with db.acquire() as conn:
        row = await conn.fetchrow(f'''SELECT p.id, p.part, p.study_support AS "studySupport"
            FROM speaking_prompts p WHERE {where} AND p.id=${len(args)}::uuid LIMIT 1''', *args)
        if not row: return core.j({'error': 'not_found'}, 404)
        support = _study_support(row['studySupport'])
        if support is None: return core.j({'error': 'invalid_study_support'}, 502)
        related = None
        target_id = core.uuid_value(row['studySupport'].get('relatedPart3Id')) if row.get('part') == 'part2' else None
        if target_id:
            target_where, target_args = _scope(channel, part='part3')
            target_args.append(target_id)
            target = await conn.fetchrow(f'''SELECT p.id, {_TOPIC_KEY} AS "topicKey"
                FROM speaking_prompts p WHERE {target_where} AND p.id=${len(target_args)}::uuid LIMIT 1''', *target_args)
            if target:
                related = {'promptId': str(target['id']), 'topicKey': target['topicKey']}
    return core.j({'promptId': str(row['id']), 'support': support,
                   **({'relatedPart3': related} if related else {})}, headers={'Cache-Control': 'no-store'})


