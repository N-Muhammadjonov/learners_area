"""Learner-facing Speaking prompt catalogue translated from the archived TS source.

Explicit reads only. The publication/deletion predicate and keyset cursor are
shared by the corresponding five Next.js endpoints. No frontend is included.
"""
from __future__ import annotations

import base64
import binascii
import json
from datetime import datetime, timezone
from typing import Any

from fastapi import APIRouter, Request
from . import main as core
from .db import row_to_dict

router = APIRouter()
PARTS = ('part1', 'part2', 'part3', 'general')


class InvalidCursor(ValueError):
    pass


def utf16_slice(value: str, limit: int) -> str:
    """Replicate JS trim().slice(0,N) (UTF-16 code units)."""
    raw = value.strip().encode('utf-16-le', 'surrogatepass')[:limit * 2]
    return raw.decode('utf-16-le', 'surrogatepass')


def _b64(payload: Any) -> str:
    raw = json.dumps(payload, ensure_ascii=False, separators=(',', ':')).encode('utf-8')
    return base64.urlsafe_b64encode(raw).decode('ascii').rstrip('=')


def _decode(raw: str) -> Any:
    if not isinstance(raw, str) or not raw.strip():
        raise InvalidCursor('invalid cursor')
    try:
        data = base64.urlsafe_b64decode(raw + '=' * (-len(raw) % 4))
        return json.loads(data.decode('utf-8'))
    except (ValueError, TypeError, UnicodeError, binascii.Error) as exc:
        raise InvalidCursor('invalid cursor') from exc


def parse_prompt_cursor(raw: str) -> list:
    value = _decode(raw)
    if (not isinstance(value, list) or len(value) != 5
        or not isinstance(value[0], str) or value[0] not in PARTS
        or type(value[1]) is not bool or not isinstance(value[2], str)
        or not isinstance(value[3], str) or not isinstance(value[4], str)):
        raise InvalidCursor('invalid prompt cursor')
    try:
        # Source's Date.parse accepts ISO timestamps emitted by Postgres.
        parsed = datetime.fromisoformat(value[3].replace('Z', '+00:00'))
        if parsed.utcoffset() is None:
            # PostgreSQL Date.parse also accepts a zone-less timestamp as local;
            # only UTC-minted cursors are generated by this implementation.
            parsed = parsed.replace(tzinfo=timezone.utc)
    except (ValueError, OverflowError):
        raise InvalidCursor('invalid prompt cursor') from None
    return value


def parse_topic_cursor(raw: str) -> str:
    value = _decode(raw)
    key = value.get('k') if isinstance(value, dict) else None
    if not isinstance(key, str) or not key:
        raise InvalidCursor('invalid topic cursor')
    return key


# Matches publication.liveWhere AND content.deletion-filter.notDeleted.
_BASE = """(
    NOT EXISTS (SELECT 1 FROM activity_events deleted_content
      WHERE deleted_content.id=md5('deleted-content:' || p.id::text)::uuid
      AND deleted_content.type='CONTENT_DELETED')
    AND (p.publication_state='published'
      OR (p.publication_state='scheduled' AND p.publish_at <= $1))
)"""


def _scope(channel: str | None = None, *, part: str | None = None,
           topic: str | None = None, search: str | None = None) -> tuple[str, list]:
    args: list = [datetime.now(timezone.utc)]
    clauses = [_BASE]
    if channel == 'ai':
        clauses.append("(p.available_in @> '[\"ai\"]'::jsonb OR p.available_in @> '[\"practice_alone\"]'::jsonb)")
    elif channel is not None:
        clauses.append("(p.available_in @> '[\"practice_alone\"]'::jsonb OR p.available_in @> '[\"live_partner\"]'::jsonb)")
    if part:
        args.append(part)
        clauses.append(f'p.part = ${len(args)}::speaking_part')
    if topic:
        args.append(topic)
        clauses.append(f'{_TOPIC_KEY} = ${len(args)}')
    if search:
        args.append('%' + search + '%')
        clauses.append(f'(p.prompt_text ILIKE ${len(args)} OR p.topic ILIKE ${len(args)})')
    return ' AND '.join(clauses), args


_TOPIC_KEY = "CASE WHEN p.topic IS NULL OR btrim(p.topic) = '' THEN '__untitled__' ELSE lower(btrim(p.topic)) END"
_SORT = "p.part, (p.external_id IS NULL) ASC, COALESCE(p.external_id, '') ASC, p.created_at ASC, p.id ASC"
_CURSOR_COLUMNS = '(p.part, (p.external_id IS NULL), COALESCE(p.external_id, \'\'), p.created_at, p.id)'


def _prompt_cursor(row) -> str:
    return _b64([row['part'], row['externalId'] is None, row['externalId'] or '', row['createdAtText'], str(row['id'])])


def _channel(req: Request):
    raw = req.query_params.get('channel')
    if raw is not None and raw not in ('practice_alone', 'ai'):
        return None
    return 'ai' if raw == 'ai' else 'practice_alone'


async def _read_page(conn, *, channel: str, part: str | None = None, topic: str | None = None,
                     search: str = '', cursor: str | None = None, live_partner=False):
    where, args = _scope(channel, part=part, topic=topic, search=search)
    scope = where
    if cursor is not None:
        fields = parse_prompt_cursor(cursor)
        args.extend(fields)
        numbers = list(range(len(args) - 4, len(args) + 1))
        key = f'(${numbers[0]}::speaking_part, ${numbers[1]}::boolean, ${numbers[2]}::text, ${numbers[3]}::timestamptz, ${numbers[4]}::uuid)'
        scope += f' AND {_CURSOR_COLUMNS} > {key}'
    select = '''p.id, p.part, p.topic, p.prompt_text AS "promptText", p.cue_card AS "cueCard",'''
    if not live_partner:
        select += ''' p.prep_seconds AS "prepSeconds", p.answer_seconds AS "answerSeconds",'''
    select += ''' p.external_id AS "externalId", to_char(p.created_at AT TIME ZONE 'UTC',
        'YYYY-MM-DD"T"HH24:MI:SS.US"Z"') AS "createdAtText"'''
    page_size = 500 if live_partner else 100
    rows = await conn.fetch(f'''SELECT {select} FROM speaking_prompts p
        WHERE {scope} ORDER BY {_SORT} LIMIT {page_size + 1}''', *args)
    matching = await conn.fetchval(f'SELECT count(*)::int FROM speaking_prompts p WHERE {where}',
                                   *args[:len(args) - (5 if cursor is not None else 0)])
    more = len(rows) > page_size
    chosen = rows[:page_size]
    keys = ('id', 'part', 'topic', 'promptText', 'cueCard') if live_partner else (
        'id', 'part', 'topic', 'promptText', 'cueCard', 'prepSeconds', 'answerSeconds')
    return {
        'questions' if live_partner else 'prompts': [{k: row_to_dict(r)[k] for k in keys} for r in chosen],
        'hasMore': more,
        'nextCursor': _prompt_cursor(chosen[-1]) if more and chosen else None,
        'matching': int(matching or 0), 'pageSize': page_size,
    }


@router.get('/api/speaking/prompts')
async def speaking_prompts(req: Request):
    user = await core.current_user(req, active=True)
    if not user: return core.auth_error()
    part = req.query_params.get('part')
    where, args = _scope()
    db = await core.pool()
    async with db.acquire() as conn:
        rows = await conn.fetch(f'''SELECT p.id, p.part, p.category, p.prompt_text AS "promptText",
           p.cue_card AS "cueCard", p.prep_seconds AS "prepSeconds",
           p.answer_seconds AS "answerSeconds", p.follow_ups AS "followUps",
           p.study_support AS "studySupport", p.external_id AS "externalId", p.topic,
           p.source_class AS "sourceClass", p.available_in AS "availableIn",
           p.is_active AS "isActive", p.publication_state AS "publicationState",
           p.publish_at AS "publishAt", p.created_at AS "createdAt"
           FROM speaking_prompts p WHERE {where} ORDER BY p.part ASC, p.created_at ASC''', *args)
    # Source filters in JavaScript AFTER fetching the published full bank.
    return core.j({'ok': True, 'prompts': [row_to_dict(r) for r in rows if not part or r['part'] == part]})


@router.get('/api/speaking/practice/questions')
async def speaking_questions(req: Request):
    user = await core.current_user(req, active=True)
    if not user: return core.auth_error()
    channel = _channel(req)
    if channel is None: return core.j({'error': 'invalid_channel'}, 400)
    db = await core.pool()
    try:
        async with db.acquire() as conn:
            data = await _read_page(conn, channel=channel, part=req.query_params.get('part'),
                                    topic=req.query_params.get('topic'),
                                    search=utf16_slice(req.query_params.get('q', ''), 120),
                                    cursor=req.query_params.get('cursor'))
    except InvalidCursor:
        return core.j({'error': 'invalid_cursor'}, 400)
    return core.j(data, headers={'Cache-Control': 'no-store'})


