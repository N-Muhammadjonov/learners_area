// Build-time transpile of the ORIGINAL Reading dictionaries (main's src/lib/i18n/{en,uz}.ts).
// Output is a Reading-only overlay loaded lazily by Reading routes; the shared js/i18n bundle is not changed,
// so completed Listening/Vocabulary/etc. text stays byte-identical.
// Usage: node scripts/convert-reading-i18n.mjs <source-root>   (source-root contains src/lib/i18n/)
import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';
const base=path.resolve(import.meta.dirname,'..');
const source=path.resolve(process.argv[2]??path.join(base,'../..'));
const transpile=p=>ts.transpileModule(fs.readFileSync(path.join(source,p),'utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
for(const lang of ['en','uz']){
 const code=transpile('src/lib/i18n/'+lang+'.ts').replace(/export\s+type[^;]*;?/g,'').replace(/^import[^;]*;\s*$/gm,'');
 fs.writeFileSync(path.join(base,'js/i18n/reading-'+lang+'.js'),'// Generated by scripts/convert-reading-i18n.mjs from the original src/lib/i18n/'+lang+'.ts. Do not edit.\n'+code.replace(/export default (\w+);?\s*$/m,'export default $1;\n'));
}
console.log('reading dictionaries written');
