// Build-time transpile of PURE original Reading library modules (no server, database or secret imports) from main's
// src/lib into js/generated/reading-lib/. Answer keys never reach the browser: these modules describe question
// types, stimulus rebuilding, timers and labels. Server-only modules are deliberately NOT listed here.
// Usage: node scripts/convert-reading-lib.mjs <source-root>   (source-root contains src/lib/)
import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';
const base=path.resolve(import.meta.dirname,'..');
const source=path.resolve(process.argv[2]??path.join(base,'../..'));
const MODULES=['content/question-types','services/reading/grading','reading/question-model','reading/stimulus','reading/timer','reading-labels','reading-choices','reading/unstated','reading/academic-selection','services/lexical/occurrence-spans','reading/dropdowns'];
const flat=m=>m.split('/').pop();
const outDir=path.join(base,'js/generated/reading-lib');fs.mkdirSync(outDir,{recursive:true});
const known=new Set(MODULES.map(flat));
for(const m of MODULES){
 const src=fs.readFileSync(path.join(source,'src/lib',m+'.ts'),'utf8');
 let out=ts.transpileModule(src,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
 out=out.replace(/from\s*"(@\/lib\/([^"]+)|\.\/([^"]+))"/g,(match,full,lib,rel)=>{const target=flat(lib??rel);if(!known.has(target))throw Error('unlisted import in '+m+': '+full);return `from "./${target}.js"`;});
 out=out.replace(/from\s*'(@\/lib\/([^']+)|\.\/([^']+))'/g,(match,full,lib,rel)=>{const target=flat(lib??rel);if(!known.has(target))throw Error('unlisted import in '+m+': '+full);return `from "./${target}.js"`;});
 if(/from\s*["']server-only["']|from\s*["']next|from\s*["']react["']|drizzle-orm|@\/db\//.test(out))throw Error('server import in '+m);
 fs.writeFileSync(path.join(outDir,flat(m)+'.js'),'// Generated by scripts/convert-reading-lib.mjs from the original src/lib/'+m+'.ts. Do not edit.\n'+out);
}
console.log('reading library modules written:',MODULES.length);
