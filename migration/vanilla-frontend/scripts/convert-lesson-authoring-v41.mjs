// V41: extract the small, pure vocabularies the Lessons author desk needs from the ORIGINAL
// TypeScript sources, so the vanilla desk never keeps a drifting copy of block types, learning
// areas or question types. Output is a generated module; the server still validates everything.
import fs from 'node:fs';
import path from 'node:path';
const base = path.resolve(import.meta.dirname, '..');
const root = path.resolve(base, '../..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');

function arrayOf(source, name) {
  const m = source.match(new RegExp(`${name}\\s*=\\s*\\[([\\s\\S]*?)\\]\\s*(as const)?;`));
  if (!m) throw new Error(`Missing ${name}`);
  return [...m[1].matchAll(/"([^"]+)"/g)].map(x => x[1]);
}

const blocks = arrayOf(read('src/lib/content/blocks.ts'), 'LESSON_BLOCK_TYPES');
const areaSource = read('src/lib/content/learning-areas.ts');
const areas = arrayOf(areaSource, 'LEARNING_AREAS');
const areaLabels = {};
for (const m of areaSource.matchAll(/^\s*(\w+): \{ en: "([^"]+)", uz: "([^"]+)" \},?$/gm)) areaLabels[m[1]] = { en: m[2], uz: m[3] };
for (const area of areas) if (!areaLabels[area]) throw new Error(`No label for ${area}`);

const questionSource = read('src/lib/content/question-types.ts');
const questionTypes = [...questionSource.matchAll(/defineQuestionType\(\{\s*id: "([^"]+)",\s*module: "([^"]+)",\s*label: "([^"]+)"/g)]
  .map(m => ({ id: m[1], module: m[2], label: m[3] }));
if (questionTypes.length < 10) throw new Error('Unexpected question type count');

const out = `// GENERATED by scripts/convert-lesson-authoring-v41.mjs from the original TypeScript sources.
// Do not edit by hand. Pure data: no database, grading or validation rules live here.
export const LESSON_BLOCK_TYPES = ${JSON.stringify(blocks)};
export const LEARNING_AREAS = ${JSON.stringify(areas)};
export const LEARNING_AREA_LABELS = ${JSON.stringify(areaLabels, null, 2)};
export const QUESTION_TYPES = ${JSON.stringify(questionTypes)};
`;
fs.mkdirSync(path.join(base, 'js/generated'), { recursive: true });
fs.writeFileSync(path.join(base, 'js/generated/lesson-authoring-constants.js'), out);
console.log(`lesson-authoring constants: ${blocks.length} block types, ${areas.length} areas, ${questionTypes.length} question types`);
