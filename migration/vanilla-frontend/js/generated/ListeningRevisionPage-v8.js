import {h,fragment,Link} from '../native.js';import {ListeningMap} from './listening-map.js';import {occurrenceSpans} from './listening-occurrence-spans.js';
import {Card,EmptyState} from './ui.js';import {Button} from '../../modules/shared/presentation.js';import {Input} from '../../modules/shared/inputs.js';
export function render(scope) {
    const { dict, attempt, test, questions, mistakeMap, keywords, speed, mcq, vocabulary, SpeedTrainer, McqMastery, ClickableText } = scope;
    const typeLabel = dict.listening.type;
    const supportsRateControl = kind => ["audio", "file", "video"].includes(kind);
    return (h("div", { className: "mx-auto flex max-w-3xl flex-col gap-4" },
        h("div", { className: "flex flex-wrap items-center justify-between gap-2" },
            h("div", null,
                h("h1", { className: "font-display text-2xl text-ink-900" }, dict.listening.revisionStudio),
                h("p", { className: "text-sm text-ink-500" }, test.title)),
            h(Link, { href: `/app/listening/attempts/${attempt.id}`, className: "btn-secondary ", "data-back-to-analysis": true }, dict.listening.backToAnalysis)),
        h("p", { className: "text-sm text-ink-500" }, dict.listening.revisionSubtitle),
        h(Card, { "data-mistake-map": true },
            h("div", { className: "flex flex-wrap items-center justify-between gap-2" },
                h("h2", { className: "font-display text-lg text-ink-900" }, dict.listening.mistakeMap),
                h("span", { className: "text-xs text-ink-300" }, dict.listening.mistakeMapHint)),
            mistakeMap.byType.length === 0 ? (h("p", { className: "mt-2 text-sm text-ink-500", "data-mistake-empty": true }, dict.listening.mistakeMapEmpty)) : (h(fragment, null,
                mistakeMap.weakest && (h("p", { className: "mt-2 text-sm text-ink-700", "data-weakest-type": mistakeMap.weakest.type },
                    dict.listening.weakestType,
                    ": ",
                    typeLabel[mistakeMap.weakest.type],
                    " \u00B7",
                    " ",
                    Math.round(mistakeMap.weakest.accuracy * 100),
                    "%")),
                h("div", { className: "mt-3 flex flex-col gap-2" }, mistakeMap.byType.map((row) => (h("div", { key: row.type, "data-type-accuracy": row.type },
                    h("div", { className: "flex items-center justify-between text-xs text-ink-500" },
                        h("span", null, typeLabel[row.type]),
                        h("span", null,
                            row.correct,
                            "/",
                            row.total,
                            " \u00B7 ",
                            dict.listening.attemptsCounted)),
                    h("div", { className: "mt-1 h-2 w-full rounded-sm bg-paper-sunken" },
                        h("div", { className: "h-2 rounded-sm bg-signal-600", style: { width: `${Math.round(row.accuracy * 100)}%` } })))))))),
            mistakeMap.recent.length > 0 && (h("div", { className: "mt-4" },
                h("h3", { className: "mb-2 text-sm font-semibold text-ink-700" }, dict.listening.missedQuestions),
                h("ul", { className: "flex flex-col divide-y divide-ink-100" }, mistakeMap.recent.map((m) => (h("li", { key: m.questionId, className: "py-2", "data-mistake": m.questionId },
                    h("p", { className: "text-sm text-ink-900" }, m.questionText),
                    h("p", { className: "text-xs text-ink-500" },
                        dict.listening.yourAnswer,
                        ": ",
                        h("span", { className: "text-ink-900" }, m.userAnswer || "—"),
                        " \u00B7",
                        " ",
                        dict.listening.correctAnswer,
                        ": ",
                        h("span", { className: "text-ink-900" }, m.correctAnswer)),
                    h(ClickableText, { dict: dict, text: m.explanation, sourceType: "listening", sourceId: test.id, className: "text-xs leading-relaxed text-ink-300" })))))))),
        h(Card, { "data-keyword-table": true },
            h("h2", { className: "font-display text-lg text-ink-900" }, dict.listening.keywordsTitle),
            h("p", { className: "mt-1 text-xs text-ink-300" }, dict.listening.keywordsHint),
            keywords.length === 0 ? (h("p", { className: "mt-2 text-sm text-ink-500", "data-keywords-empty": true }, dict.listening.keywordsEmpty)) : (h("div", { className: "mt-3 flex flex-col gap-3" }, keywords.map((entry) => (h("div", { key: entry.id, className: "rounded-sm bg-paper-sunken p-3", "data-keyword-row": entry.id },
                h("p", { className: "text-sm text-ink-900" },
                    entry.order,
                    ". ",
                    entry.questionText),
                entry.keywords.length > 0 && (h("div", { className: "mt-1 flex flex-wrap items-center gap-1" },
                    h("span", { className: "text-xs text-ink-300" },
                        dict.listening.keywordsLabel,
                        ":"),
                    entry.keywords.map((word) => (h("span", { key: word, className: "badge bg-paper text-ink-700" }, word))))),
                entry.paraphrases.length > 0 && (
                /* A phone is narrower than a two-column table: scroll, never clip. */
                h("div", { className: "mt-2 overflow-x-auto" },
                    h("table", { className: "w-full min-w-[280px] text-left text-xs" },
                        h("thead", null,
                            h("tr", { className: "text-ink-300" },
                                h("th", { className: "font-medium" }, dict.listening.heardLabel),
                                h("th", { className: "font-medium" }, dict.listening.askedLabel))),
                        h("tbody", { className: "text-ink-700" }, entry.paraphrases.map((pair) => (h("tr", { key: `${pair.heard}-${pair.asked}` },
                            h("td", { className: "py-0.5 pr-2" }, pair.heard),
                            h("td", { className: "py-0.5" }, pair.asked)))))))))))))),
        h(SpeedTrainer, { sourceId: attempt.id, dict: dict, audioUrl: test.audioUrl, rateControlSupported: supportsRateControl(test.audioType), status: speed, transcript: test.transcript }),
        h(McqMastery, { dict: dict, questions: mcq }),
        h(Card, { "data-test-vocabulary": true },
            h("div", { className: "flex flex-wrap items-center justify-between gap-2" },
                h("h2", { className: "font-display text-lg text-ink-900" }, dict.listening.wordsFromTest),
                h(Link, { href: "/app/vocabulary?panel=my-words", className: "btn-secondary ", "data-vocabulary-link": true },
                    dict.nav.vocabulary,
                    " \u2192")),
            h("p", { className: "mt-1 text-xs text-ink-300" }, dict.listening.wordsFromTestHint),
            vocabulary.length === 0 ? (h("p", { className: "mt-2 text-sm text-ink-500", "data-vocabulary-empty": true }, dict.listening.mistakeMapEmpty)) : (h("ul", { className: "mt-2 flex flex-wrap gap-2" }, vocabulary.map((word) => (h("li", { key: word.id, className: "flex items-center gap-1", "data-test-word": word.term },
                h("span", { className: "badge bg-paper-sunken text-ink-700" }, word.term),
                word.translationUz && h("span", { className: "text-xs text-ink-300" }, word.translationUz))))))),
        questions.length === 0 && h(EmptyState, { title: dict.listening.mcqEmpty })));
}
