import {h,fragment} from '../native.js';
export function render(scope) {
    const { dict, t, word, onClose, position, popupRef, error, loading, busy, setLookupVersion, known, saved, unresolved, contextual, catalogueLookup, meaning, setMeaning, uzbek, setUzbek, folderId, setFolderId, sourceType, folders, save, speak, needsMeaning } = scope;
    return h("div", { ref: popupRef, tabIndex: -1, role: "dialog", "aria-label": word, "data-word-popover": true, style: { left: position?.left ?? 0, top: position?.top ?? 0, visibility: position ? "visible" : "hidden", maxHeight: "calc(100dvh - 16px)" }, className: "fixed z-50 w-[min(20rem,calc(100vw-16px))] overflow-y-auto whitespace-normal rounded-md border border-ink-100 bg-paper-raised p-3 shadow-raised" },
        h("div", { className: "flex items-start justify-between gap-2" },
            h("span", { className: "font-display text-lg text-ink-900" }, word),
            h("button", { type: "button", className: "btn-ghost px-2 py-1 text-xs", "aria-label": t.games.pronounce, onClick: () => speak(word) }, "\uD83D\uDD0A"),
            h("button", { type: "button", className: "btn-ghost px-2 py-1 text-xs", onClick: onClose }, t.add.close)),
        error && h("div", { className: "mt-2 text-xs text-band-warn" },
            h("p", { role: "alert" }, error),
            h("button", { type: "button", className: "btn-ghost mt-1 text-xs", disabled: loading || busy, onClick: () => setLookupVersion((value) => value + 1) }, dict.errorPage.retry)),
        loading && h("p", { className: "mt-2 text-xs text-ink-300" }, dict.common.loading),
        !loading && known && (h("div", { className: "mt-2 flex flex-col gap-1 text-xs" },
            h("p", { className: "text-ink-700" }, known.definitionEn),
            known.translationUz && h("p", { className: "text-ink-500" }, known.translationUz),
            h("p", { className: "text-ink-300" },
                t.tab.words,
                " \u00B7 ",
                t.mastery[known.mastery] ?? known.mastery))),
        !loading && !known && !saved && (h("div", { className: "mt-2 flex flex-col gap-2" },
            unresolved && h("div", { role: "status", className: "text-xs text-ink-500", "data-word-unresolved": true },
                h("p", { className: "font-medium text-ink-700" }, t.meaningUnchecked),
                h("p", null, t.meaningUncheckedHint)),
            contextual ? h("div", { className: "text-sm text-ink-700" },
                (contextual.partOfSpeech || contextual.lexicalType || contextual.ipa) && h("p", { className: "text-xs text-ink-500", "data-word-lexical": true },
                    [contextual.partOfSpeech, contextual.lexicalType && contextual.lexicalType !== "word" ? t.lexicalTypeLabel[contextual.lexicalType] ?? null : null].filter(Boolean).join(" · "),
                    contextual.ipa && h("span", { className: "ml-1 font-mono", "data-word-ipa": true },
                        "/",
                        contextual.ipa,
                        "/")),
                h("p", null, contextual.definitionEn),
                contextual.translationUz && h("p", null, contextual.translationUz),
                h("p", { className: "mt-1 text-xs text-ink-500" }, catalogueLookup ? contextual.sourceLabel : contextual.verificationStatus === "verified" ? t.contextVerified : t.contextUnverified)) : h(fragment, null,
                h("label", { className: "text-xs text-ink-500" },
                    t.add.definition,
                    h("input", { className: "input mt-1", value: meaning, onChange: (event) => setMeaning(event.target.value) })),
                h("label", { className: "text-xs text-ink-500" },
                    t.add.translation,
                    h("input", { className: "input mt-1", value: uzbek, onChange: (event) => setUzbek(event.target.value) }))),
            h("label", { className: "text-xs text-ink-500" },
                t.games.set.folder,
                h("select", { className: "input mt-1", value: folderId, onChange: (event) => setFolderId(event.target.value) },
                    h("option", { value: "" }, sourceType === "listening" ? "Listening" : sourceType === "reading" ? "Reading" : t.folders.unassigned),
                    folders.map((folder) => h("option", { key: folder.id, value: folder.id }, folder.name)))),
            h("div", { className: "flex items-center gap-2" },
                h("button", { type: "button", className: "btn-primary text-xs", disabled: busy, "data-word-save": true, onClick: () => void save() }, busy ? dict.common.saving : t.add.button)))),
        saved && (h("p", { className: "mt-2 text-xs text-band-good", "data-word-saved": true },
            t.add.added,
            " \u00B7 ",
            t.tab.words)),
        needsMeaning && (h("p", { className: "mt-2 text-xs text-band-warn", "data-word-needs-meaning": true }, t.add.needsMeaning)));
}
