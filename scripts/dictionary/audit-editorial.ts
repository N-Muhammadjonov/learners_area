import { readFileSync,writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";
import { decodeShard } from "../../src/lib/dictionary/shards";
import { dictionaryPresentation } from "../../src/lib/dictionary/presentation";
import { auditDictionaryEditorial,type EditorialReview,type MaterialText } from "../../src/lib/dictionary/editorial-audit";
const [prepared,corpusFile,sourceHashesFile,reviewFile,out,flag]=process.argv.slice(2);
if(!prepared||!corpusFile||!sourceHashesFile||!reviewFile||!out||flag&&flag!=="--require-complete")throw Error("Usage: audit-editorial.ts PREPARED CORPUS SOURCE-HASHES REVIEWS REPORT [--require-complete]");
const read=(path:string)=>JSON.parse(readFileSync(path,"utf8"));
const plan=read(join(prepared,"release-plan.json"));
const entries=plan.shards.flatMap((descriptor:import("../../src/lib/dictionary/shards").ShardDescriptor)=>[...decodeShard(plan.release,descriptor,readFileSync(join(prepared,"shards",descriptor.shard+".json.gz"))).values()]);
if(entries.length!==plan.expected.lexemes)throw Error("full_dictionary_inventory_required");
const corpus=read(corpusFile) as {texts:MaterialText[]};
const sourceHashes=read(sourceHashesFile) as {readingBodyFingerprint:string;rows:{source:string;id:string;body_md5:string}[]};
const ids=new Set(sourceHashes.rows.map(row=>row.source+":"+row.id));
const materials=corpus.texts.filter(text=>text.source==="reading"||ids.has(text.source+":"+text.id));
const md5=(text:string)=>createHash("md5").update(text).digest("hex");
for(const text of materials.filter(text=>text.source!=="reading"))if(sourceHashes.rows.find(row=>row.source===text.source&&row.id===text.id)?.body_md5!==md5(text.body))throw Error("material_snapshot_drift:"+text.id);
const readingFingerprint=md5(materials.filter(text=>text.source==="reading").sort((a,b)=>a.id.localeCompare(b.id,"en")).map(text=>text.id+":"+text.body).join("\n"));
if(readingFingerprint!==sourceHashes.readingBodyFingerprint)throw Error("reading_snapshot_drift");
const reviews=read(reviewFile) as EditorialReview;
const report=auditDictionaryEditorial({entries,presentation:dictionaryPresentation,materials,reviews,expectedMaterials:{reading:105,listening:32,retention:75}});
writeFileSync(out,JSON.stringify({sourceRelease:plan.release,...report},null,2)+"\n");
const {materialRows,queues,missingDictionaryForms,...summary}=report;
console.log(JSON.stringify({...summary,missingDictionaryForms:missingDictionaryForms.length}));
if(flag==="--require-complete"&&!report.readyForManualCheck)process.exitCode=1;
